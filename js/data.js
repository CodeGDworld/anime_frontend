/**
 * Helper to fetch anime items by category
 */
export function getAnimeByCategory(categoryId) {
  return ANIME_DATABASE.filter(item => item.category === categoryId);
}

/**
 * Helper to get a single anime by ID
 */
export function getAnimeById(id) {
  return ANIME_DATABASE.find(item => item.id === id);
}

/**
 * Search anime across all titles, studios, tags, and moves
 */
export function searchAnime(query) {
  if (!query || !query.trim()) return [];
  const q = query.toLowerCase().trim();
  return ANIME_DATABASE.filter(item => 
    item.title.toLowerCase().includes(q) ||
    item.japaneseTitle.toLowerCase().includes(q) ||
    item.studio.toLowerCase().includes(q) ||
    item.signatureMove.toLowerCase().includes(q) ||
    item.tags.some(t => t.toLowerCase().includes(q)) ||
    item.description.toLowerCase().includes(q)
  );
}
